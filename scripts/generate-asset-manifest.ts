// Generates docs/ASSET-MANIFEST.md (human-readable) and docs/asset-manifest.json
// from the project data, and checks that every referenced file exists.
//   npm run assets:manifest
import { existsSync, mkdirSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { projects } from "../data/projects";
import { stories } from "../data/stories";
import { IMAGE_KIND_LABELS, type ProjectImage } from "../types/project";

const root = path.resolve(import.meta.dirname, "..");
const pub = (p: string) => path.join(root, "public", p);

interface Row {
  project: string;
  file: string;
  source: string;
  placement: string;
  verification: string;
  type: string;
  permission: string;
  alt: string;
  note: string;
  exists: boolean;
  sizeKb: number;
}

const rows: Row[] = [];
const add = (project: string, img: ProjectImage, placement: string) => {
  const exists = existsSync(pub(img.src));
  rows.push({
    project,
    file: img.src,
    source: img.source,
    placement,
    verification: img.verification,
    type: IMAGE_KIND_LABELS[img.kind],
    permission: img.permission,
    alt: img.alt,
    note: img.note ?? "",
    exists,
    sizeKb: exists ? Math.round(statSync(pub(img.src)).size / 1024) : 0,
  });
};

for (const p of projects) {
  for (const img of p.gallery) {
    add(p.name, img, img.src === p.heroImage.src ? "Hero + gallery" : "Gallery");
  }
  if (!p.gallery.some((g) => g.src === p.heroImage.src)) add(p.name, p.heroImage, "Hero");
  for (const img of p.floorPlans ?? []) add(p.name, img, img.kind === "floor-plan" ? "Floor plans" : "Masterplans");
}

// Gohar Stories images that are not project images.
const storyRows = stories.flatMap((s) =>
  [s.cover, ...s.blocks.flatMap((b) => (b.type === "image" ? [b.image] : []))].map((img) => ({
    story: s.title,
    file: img.src,
    alt: img.alt,
    credit: img.credit,
    exists: existsSync(pub(img.src)),
    sharedWithProject: rows.some((r) => r.file === img.src),
  })),
);

const brand = [
  { file: "/images/brand/gohar-logo-dark.png", note: "Header on light backgrounds" },
  { file: "/images/brand/gohar-logo-light.png", note: "Header over imagery, footer" },
];

const brochures = projects
  .filter((p) => p.brochure)
  .map((p) => ({ project: p.name, ...p.brochure!, exists: existsSync(pub(p.brochure!.href)) }));

const missing = [...rows.filter((r) => !r.exists), ...storyRows.filter((r) => !r.exists)];
const needsConfirmation = rows.filter((r) => r.verification !== "verified-official");
const photoCount = rows.filter((r) => r.type === IMAGE_KIND_LABELS.photograph).length;

const esc = (s: string) => s.replace(/\|/g, "\\|");
const md = `# Asset manifest

Generated by \`npm run assets:manifest\` from \`data/projects.ts\`. Do not edit by hand.

- Project images: **${rows.length}** (${photoCount} photographs, ${rows.length - photoCount} renders or masterplans)
- Missing files: **${missing.length}**
- Images needing client confirmation: **${needsConfirmation.length}**
- Brochures / documents: **${brochures.length}**

All images were published by Gohar Group of Companies on https://gohargoc.com/ (retrieved 22 Oct 2026).
Permission status "assumed-client-owned" means the company published them on its own website.
Written confirmation of usage rights is still recommended before launch.

## Brand

| File | Use | Source |
| --- | --- | --- |
${brand.map((b) => `| \`${b.file}\` | ${b.note} | https://gohargoc.com/ (official logo) |`).join("\n")}
| \`/app/icon.png\`, \`/app/apple-icon.png\` | Favicon (red "A" cropped from the official logo by \`scripts/generate-icons.mjs\`) | Derived. Needs client approval |

## Project images

| Project | File | Type | Placement | Verification | Permission | Size | Source | Alt text | Notes |
| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |
${rows
  .map(
    (r) =>
      `| ${esc(r.project)} | \`${r.file}\` | ${r.type} | ${r.placement} | ${r.verification} | ${r.permission} | ${r.sizeKb} KB | ${r.source} | ${esc(r.alt)} | ${esc(r.note)}${r.exists ? "" : " **MISSING FILE**"} |`,
  )
  .join("\n")}

## Gohar Stories images

Story covers that are also project images are listed above with their source. The two event photographs
come from the official WordPress posts (\`/wp-content/uploads/2026/07/\`).

| Story | File | Credit | Shared with a project | Present |
| --- | --- | --- | --- | --- |
${storyRows.map((r) => `| ${esc(r.story)} | \`${r.file}\` | ${r.credit} | ${r.sharedWithProject ? "yes" : "no"} | ${r.exists ? "yes" : "**no**"} |`).join("\n")}

## Documents

| Project | File | Label | Source | Present |
| --- | --- | --- | --- | --- |
${brochures.map((b) => `| ${esc(b.project)} | \`${b.href}\` | ${b.label} (${b.sizeLabel ?? ""}) | ${b.source} | ${b.exists ? "yes" : "**no**"} |`).join("\n")}

## Gaps (what is still needed)

${projects
  .map((p) => {
    const gaps: string[] = [];
    if (!p.gallery.some((g) => g.kind === "photograph")) gaps.push("no real photographs (renders only)");
    if (p.gallery.length < 3) gaps.push(`only ${p.gallery.length} image(s)`);
    if (!p.brochure) gaps.push("no brochure");
    if (!p.unitTypes?.length) gaps.push("no layout / unit information");
    if (!p.floorPlans?.some((f) => f.kind === "floor-plan")) gaps.push("no floor plans");
    return gaps.length ? `- **${p.name}**: ${gaps.join("; ")}.` : `- **${p.name}**: no gaps recorded.`;
  })
  .join("\n")}
`;

mkdirSync(path.join(root, "docs"), { recursive: true });
writeFileSync(path.join(root, "docs", "ASSET-MANIFEST.md"), md);
writeFileSync(path.join(root, "docs", "asset-manifest.json"), JSON.stringify({ images: rows, storyImages: storyRows, brand, documents: brochures }, null, 2));
console.log(`Wrote docs/ASSET-MANIFEST.md (${rows.length} images, ${missing.length} missing, ${needsConfirmation.length} need confirmation).`);
if (missing.length) process.exitCode = 1;
