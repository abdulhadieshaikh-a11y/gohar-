// Writes docs/IMAGE-USAGE.md: which authentic project image the homepage uses in each
// section (from lib/image-plan.ts), so repetition can be reviewed.   npm run images:plan
import { writeFileSync } from "node:fs";
import path from "node:path";
import { projects } from "../data/projects";
import { planHome } from "../lib/image-plan";

const plan = planHome(projects);
const name = (slug: string) => projects.find((p) => p.slug === slug)?.name ?? slug;
const rows = plan.record.map((r) => `| ${r.section} | ${name(r.project)} | \`${r.src}\` |`).join("\n");
const repeats = plan.repeats.length
  ? plan.repeats
      .map((src) => {
        const p = projects.find((x) => x.gallery.some((g) => g.src === src));
        return `- \`${src}\`: ${p?.name} has ${p?.gallery.length} published image(s), all already in use.`;
      })
      .join("\n")
  : "- None.";

const md = `# Homepage image usage

Generated by \`npm run images:plan\` from \`lib/image-plan.ts\`. Do not edit by hand.

Sections in page order. Each pick takes the project's least-used authentic image, so the same photograph is
not shown in nearby sections. Tests in \`tests/image-plan.test.ts\` enforce this.

| Section | Project | Image |
| --- | --- | --- |
${rows}

## Repeated images (unavoidable)

${repeats}

More photographs for these projects would remove the remaining repeats.
`;
writeFileSync(path.resolve(import.meta.dirname, "..", "docs", "IMAGE-USAGE.md"), md);
console.log(`Wrote docs/IMAGE-USAGE.md (${plan.record.length} placements, ${plan.repeats.length} repeated images).`);
